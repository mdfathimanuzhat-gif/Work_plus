"""PostgreSQL engine and session factory.

The engine is created from DATABASE_URL. Connections are checked with
pool_pre_ping so stale sockets are discarded. get_db is the FastAPI
dependency later modules will use; no business queries live here.
"""

from collections.abc import Generator

from sqlalchemy import create_engine
from sqlalchemy.orm import Session, sessionmaker

from app.core.config import get_settings

settings = get_settings()

engine = create_engine(
    settings.DATABASE_URL,
    pool_pre_ping=True,
)

SessionLocal = sessionmaker(autocommit=False, autoflush=False, bind=engine)


def get_db() -> Generator[Session, None, None]:
    db = SessionLocal()
    try:
        yield db
    finally:
        db.close()
